#!/usr/bin/env python3
"""Single per-case configuration: load, inspect, and render a container input.

Each cases/<case>/case.yaml has two top-level sections:

  bench:     upstream URL, pinned source/target SHAs, fix, forbidden human
             backports, difficulty. Never mounted into a run container.
  pipeline:  issue description, build/test commands, advanced flags and model
             as consumed by auto_bug_fix.

``render`` writes cases/<case>/run/, the only directory mounted into the run
container (at /case). It contains the pipeline section with the repository,
branches and fix fields derived from ``bench``, plus the fix patch for
patch-mode cases. Rendering refuses to emit any bench-only value.

Usage:
  case_config.py list
  case_config.py get <case> <dotted.key>      # resolves inside bench:
  case_config.py render <case>
  case_config.py validate [case...]
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CASES = ROOT / "cases"

REPOSITORY = {
    "source_path": "${BACKPORT_REPOS}/repo.git",
    "workdir": "${BACKPORT_WORK}",
}
PIPELINE_ORDER = (
    "issue_id",
    "bug_description",
    "build",
    "advanced",
    "model",
)


def case_file(case: str) -> Path:
    return CASES / case / "case.yaml"


def load(case: str) -> dict:
    path = case_file(case)
    if not path.is_file():
        raise SystemExit(f"unknown case: {case}")
    data = yaml.safe_load(path.read_text()) or {}
    for section in ("bench", "pipeline"):
        if section not in data:
            raise SystemExit(f"{path}: missing '{section}:' section")
    return data


def cases() -> list[str]:
    return sorted(p.parent.name for p in CASES.glob("*/case.yaml"))


def get(case: str, dotted: str) -> str:
    value = load(case)["bench"]
    for part in dotted.split("."):
        if not isinstance(value, dict) or part not in value:
            raise SystemExit(f"{case}: bench.{dotted} is not set")
        value = value[part]
    return str(value)


def get_opt(case: str, dotted: str) -> str:
    try:
        return get(case, dotted)
    except SystemExit:
        return ""


def _pipeline_doc(case: str, data: dict) -> dict:
    bench = data["bench"]
    pipeline = data["pipeline"]
    source = bench["source"]
    doc: dict = {}
    for key in PIPELINE_ORDER:
        if key in pipeline:
            doc[key] = pipeline[key]
    doc["repository"] = dict(REPOSITORY)
    branches = {"source": source["branch"]}
    if "targets" in bench:
        branches["targets"] = [t["branch"] for t in bench["targets"]]
    else:
        branches["target"] = bench["target"]["branch"]
    doc["branches"] = branches
    fix = bench.get("fix") or {"kind": "commit"}
    if fix.get("kind") == "patch":
        rendered_fix = {"patch": "./fix.patch"}
        if fix.get("upstream_ref"):
            rendered_fix["upstream_ref"] = fix["upstream_ref"]
    else:
        rendered_fix = {"commit": source["sha"]}
    doc["fix"] = rendered_fix
    return doc


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def dump(doc: dict) -> str:
    return yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=10**9)


def _leak_tokens(case: str, data: dict) -> list[str]:
    bench = data["bench"]
    tokens = list(bench.get("forbidden") or [])
    tokens.append(bench["target"]["sha"] if "target" in bench else "")
    for target in bench.get("targets") or []:
        tokens.append(target["sha"])
    upstream = bench["upstream"]
    host = upstream.split("//", 1)[-1].split("/", 1)[0]
    tokens.extend([upstream, host])
    return [t for t in tokens if t]


def render(case: str) -> Path:
    data = load(case)
    out = CASES / case / "run"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    doc = _pipeline_doc(case, data)
    header = f"# Generated by scripts/render-case.sh for {case}. Do not edit.\n"
    (out / "case.yaml").write_text(header + dump(doc))

    fix = data["bench"].get("fix") or {}
    if fix.get("kind") == "patch":
        shutil.copy2(CASES / case / "fix.patch", out / "fix.patch")
    tests_patch = data["bench"].get("tests_patch")
    if tests_patch:
        shutil.copy2(ROOT / tests_patch, out / Path(tests_patch).name)

    tokens = _leak_tokens(case, data)
    for path in out.rglob("*"):
        if not path.is_file():
            continue
        text = path.read_text(errors="replace")
        for token in tokens:
            if token and token in text:
                shutil.rmtree(out)
                raise SystemExit(
                    f"{case}: rendered {path.name} contains bench-only value {token!r}"
                )
        human = _human_leak(case, text)
        if human:
            shutil.rmtree(out)
            raise SystemExit(
                f"{case}: rendered {path.name} contains human backport line {human!r}"
            )
    print(out)
    return out


def _human_lines(case: str) -> list[str]:
    """Distinctive added lines from the recorded human backport, if any.

    Lines the source fix also contains are excluded: for patch-mode cases the
    source fix is mounted on purpose, and sharing text with the human backport
    is not a leak.
    """
    patch = CASES / case / "human" / "human.patch"
    if not patch.is_file():
        return []
    source = "\n".join(
        path.read_text(errors="replace")
        for path in sorted((CASES / case).glob("*.patch"))
    )
    lines = []
    for line in patch.read_text(errors="replace").splitlines():
        if not line.startswith("+") or line.startswith("+++"):
            continue
        body = line[1:].strip()
        if len(body) >= 50 and body not in source:
            lines.append(body)
    return sorted(set(lines))[:5000]


def _human_leak(case: str, text: str) -> str | None:
    for line in _human_lines(case):
        if line in text:
            return line
    return None


def check_render(case: str) -> None:
    """Fail if the rendered run directory still contains bench-only values."""
    data = load(case)
    out = CASES / case / "run"
    if not out.is_dir():
        raise SystemExit(f"{case}: run/ is missing; run render-case.sh {case}")
    tokens = _leak_tokens(case, data)
    for path in out.rglob("*"):
        if not path.is_file():
            continue
        text = path.read_text(errors="replace")
        for token in tokens:
            if token and token in text:
                raise SystemExit(f"{case}: run/{path.name} contains {token!r}")
        human = _human_leak(case, text)
        if human:
            raise SystemExit(f"{case}: run/{path.name} contains human backport line {human!r}")


def validate(case: str) -> None:
    data = load(case)
    bench = data["bench"]
    errors = []
    if not bench.get("upstream", "").startswith("https://"):
        errors.append("bench.upstream must be an https URL")
    source = bench.get("source") or {}
    for key in ("branch", "sha"):
        if not source.get(key):
            errors.append(f"bench.source.{key} missing")
    targets = bench.get("targets") or ([bench["target"]] if "target" in bench else [])
    if not targets:
        errors.append("bench.target or bench.targets missing")
    for target in targets:
        for key in ("branch", "sha"):
            if not target.get(key):
                errors.append(f"bench target {target.get('branch')!r}: {key} missing")
    fix = bench.get("fix") or {"kind": "commit"}
    if fix.get("kind") == "patch":
        patch = case_file(case).parent / "fix.patch"
        if not patch.is_file():
            errors.append("patch-mode case has no fix.patch")
    elif fix.get("kind") != "commit":
        errors.append(f"unknown bench.fix.kind: {fix.get('kind')!r}")
    for sha in bench.get("forbidden") or []:
        if len(sha) != 40:
            errors.append(f"forbidden entry is not a full SHA: {sha!r}")
    human = bench.get("human") or {}
    mode = human.get("mode")
    if mode not in ("commits", "none"):
        errors.append(f"bench.human.mode must be commits|none, got {mode!r}")
    if mode == "commits" and not (human.get("commits") or bench.get("forbidden")):
        errors.append("bench.human.mode=commits requires human.commits or bench.forbidden")
    if errors:
        raise SystemExit(f"{case}: " + "; ".join(errors))


def main(argv: list[str]) -> None:
    if not argv:
        raise SystemExit(__doc__)
    cmd, args = argv[0], argv[1:]
    if cmd == "list":
        print("\n".join(cases()))
    elif cmd == "get":
        print(get(args[0], args[1]))
    elif cmd == "get-opt":
        print(get_opt(args[0], args[1]))
    elif cmd == "bench-json":
        print(json.dumps(load(args[0])["bench"]))
    elif cmd == "render":
        for case in args or cases():
            render(case)
    elif cmd == "check-render":
        for case in args or cases():
            check_render(case)
    elif cmd == "validate":
        for case in args or cases():
            validate(case)
        print("valid")
    else:
        raise SystemExit(f"unknown command: {cmd}")


if __name__ == "__main__":
    main(sys.argv[1:])
