#!/usr/bin/env bash
# Create models/models.local.yaml for this machine.
#
# Prompts for the model profile, provider, served model name, API base URL and
# API key file. If the key file does not exist, the key can be pasted in and is
# stored with 0600 permissions. The registry itself only records the key path.
#
# Usage: setup.sh [--profile ID] [--provider P] [--model M]
#                 [--api-base URL] [--api-key-file PATH] [--no-input]
set -euo pipefail

BENCH_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$BENCH_DIR/models/models.local.yaml"

profile="${SETUP_PROFILE:-deepseek-v41-flash}"
provider="${SETUP_PROVIDER:-litellm}"
model="${SETUP_MODEL:-}"
api_base="${SETUP_API_BASE:-}"
key_file="${SETUP_API_KEY_FILE:-}"
interactive=1

die() { printf 'setup: %s\n' "$*" >&2; exit 1; }

while [ "$#" -gt 0 ]; do
  case "$1" in
    --profile) profile="$2"; shift 2 ;;
    --provider) provider="$2"; shift 2 ;;
    --model) model="$2"; shift 2 ;;
    --api-base) api_base="$2"; shift 2 ;;
    --api-key-file) key_file="$2"; shift 2 ;;
    --no-input) interactive=0; shift ;;
    -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done

ask() { # ask <prompt> <current value>
  local reply
  if [ "$interactive" = 1 ] && [ -t 0 ]; then
    read -r -p "$1${2:+ [$2]}: " reply || true
    printf '%s' "${reply:-$2}"
  else
    printf '%s' "$2"
  fi
}

profile="$(ask "Profile id" "$profile")"
case "$profile" in
  ""|*[!A-Za-z0-9_.-]*) die "profile id may use letters, digits, '_', '.' and '-'" ;;
esac
provider="$(ask "Provider (litellm, anthropic, ...)" "$provider")"
model="$(ask "Served model id (e.g. openai/my-model)" "$model")"
api_base="$(ask "API base URL (e.g. https://llm.example.com/v1)" "$api_base")"
[ -n "$model" ] || die "a served model id is required (pass --model)"
[ -n "$api_base" ] || die "an API base URL is required (pass --api-base)"
case "$api_base" in
  http://*|https://*) ;;
  *) die "API base URL must start with http:// or https://" ;;
esac

default_key_file="$HOME/.config/amalgamator/keys/$provider"
key_file="$(ask "API key file" "${key_file:-$default_key_file}")"
case "$key_file" in
  "~/"*) key_file="$HOME/${key_file#\~/}" ;;
esac

if [ ! -f "$key_file" ] && [ "$interactive" = 1 ] && [ -t 0 ]; then
  printf 'API key file %s does not exist.\n' "$key_file"
  read -r -s -p "Paste the API key (stored there with 0600; empty to skip): " key || true
  printf '\n'
  if [ -n "${key:-}" ]; then
    mkdir -p "$(dirname "$key_file")"
    (umask 077; printf '%s\n' "$key" > "$key_file")
    printf 'wrote %s\n' "$key_file"
  fi
fi

[ -f "$key_file" ] || printf 'warning: %s does not exist yet; create it before running a case\n' "$key_file" >&2

mkdir -p "$BENCH_DIR/models"
python3 - "$target" "$profile" "$provider" "$model" "$api_base" "$key_file" <<'PY'
import json, pathlib, sys

target, profile, provider, model, api_base, key_file = sys.argv[1:7]
q = json.dumps
text = (
    "# Generated by scripts/setup.sh. Local to this machine (gitignored).\n"
    "models:\n"
    f"  {profile}:\n"
    f"    provider: {q(provider)}\n"
    f"    model: {q(model)}\n"
    f"    api_base: {q(api_base)}\n"
    f"    api_key_file: {q(key_file)}\n"
    "    context_length: 1000000\n"
    "    params:\n"
    "      max_tokens: 32768\n"
    "      reasoning_effort: medium\n"
    f"default: {profile}\n"
)
path = pathlib.Path(target)
path.write_text(text)
path.chmod(0o600)
print(f"wrote {target}")
PY

cat <<EOF

Next steps:
  1. ${BENCH_DIR}/scripts/build-images.sh
  2. ${BENCH_DIR}/scripts/build-all.sh
  3. ${BENCH_DIR}/scripts/check-prereqs.sh
  4. ${BENCH_DIR}/scripts/run-case.sh pcre2    # quick smoke case
  5. ${BENCH_DIR}/scripts/run-suite.sh --parallel 2
EOF
